#!/usr/bin/env python3
"""Guarda enlaces reales y actualiza el anexo editable antes de recompilar."""
import argparse
import json
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parent
CONFIG = ROOT / "docs" / "enlaces_entrega.json"


def validar_url(value):
    value = value.strip()
    try:
        parsed = urlsplit(value)
    except ValueError as error:
        raise argparse.ArgumentTypeError("La URL no tiene una dirección válida.") from error
    if parsed.scheme not in {"http", "https"} or not parsed.netloc:
        raise argparse.ArgumentTypeError("Introduce una URL completa http o https.")
    if any(char in value for char in "{}\\\r\n") or any(char.isspace() for char in value):
        raise argparse.ArgumentTypeError("La URL contiene caracteres no admitidos.")
    return value


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ("overleaf", "github", "video"):
        parser.add_argument(f"--{name}", type=validar_url)
    args = parser.parse_args()
    config = json.loads(CONFIG.read_text(encoding="utf-8"))
    for name in ("overleaf", "github", "video"):
        value = getattr(args, name)
        if value is not None:
            config[name] = value
    CONFIG.write_text(json.dumps(config, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    macros = {"overleaf": "OverleafLink", "github": "GitHubLink", "video": "VideoLink"}
    lines = ["% Generated by actualizar_enlaces.py from docs/enlaces_entrega.json."]
    for name, macro in macros.items():
        value = config.get(name)
        if value:
            # urldef conserva correctamente fragmentos # y escapes % de la URL.
            lines.append("\\urldef{\\" + macro + "}\\url{" + value + "}")
        else:
            text = r"\textit{Pending " + name + " URL}"
            lines.append("\\newcommand{\\" + macro + "}{" + text + "}")
    (ROOT / "report" / "enlaces.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    md = ["# Enlaces de la entrega", "", "Python está aprobado por el docente según la confirmación del estudiante.", ""]
    for name in ("overleaf", "github", "video"):
        value = config.get(name)
        md.append(f"- {name.capitalize()}: {value if value else '**pendiente de recibir**'}")
    md.extend(["", "Después de añadir enlaces, recompila el informe y vuelve a cargar el PDF actualizado en Moodle.", ""])
    (ROOT / "docs" / "anexo_entregables.md").write_text("\n".join(md), encoding="utf-8")
    print("Enlaces y anexo actualizados. Recompila el informe para reflejarlos en el PDF.")


if __name__ == "__main__":
    main()
